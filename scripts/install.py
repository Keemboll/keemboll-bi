#!/usr/bin/env python3
"""Install a plugin's skills into a BI project for the agent of your choice.

Usage:
  python scripts/install.py --agent <agent> [--target <project folder>] [options]
  python scripts/install.py --list

Agents: claude, codex, gemini, grok, copilot, cursor, generic (see --list for folders).
Options:
  --target <folder>    BI project to install into (default: current folder)
  --global             install into the home folder (~/...) instead of the project; no AGENTS.md
  --dest <folder>      force the skills folder (overrides the agent's default)
  --plugin <name>      plugin to install (default: the only plugin in the repository)
  --skills a,b,c       install only these skills
  --no-agents-md       do not write the index block into AGENTS.md
  --force              replace a same-named skill that this script did not install
  --uninstall          remove what this script installed (skills, subagents, AGENTS.md block)
  --dry-run            show what would be done without writing anything

Skills follow the open "Agent Skills" format (a folder + SKILL.md): they are copied as is.
For agents that do not load skills by themselves, the AGENTS.md block acts as an index:
it says which SKILL.md to read before which task.
"""
import json
import os
import shutil
import sys

from common import ROOT, load_plugin, plugin_names, read_text, short_description, utf8_console, write_text

# agent -> (skills folder in the project, personal skills folder, AGENTS.md block by default)
AGENTS = {
    "claude": (".claude/skills", "~/.claude/skills", False),
    "codex": (".agents/skills", "~/.agents/skills", True),
    "gemini": (".agents/skills", "~/.agents/skills", True),
    "grok": (".grok/skills", "~/.grok/skills", True),
    "copilot": (".github/skills", "~/.copilot/skills", True),
    "cursor": (".cursor/skills", "~/.cursor/skills", True),
    "generic": (".agents/skills", "~/.agents/skills", True),
}
BEGIN = "<!-- {plugin}:begin — block generated by scripts/install.py, do not edit by hand -->"
END = "<!-- {plugin}:end -->"


def agents_md_block(plugin, skills, rel_dest):
    lines = [
        BEGIN.format(plugin=plugin["name"]),
        f"## Power BI skills — {plugin['name']} {plugin['version']}",
        "",
        f"This project ships Power BI working rules in `{rel_dest}/`. Each skill is a folder",
        "with a `SKILL.md` (instructions) and `references/` (details, read only when needed).",
        "",
        "**Before touching the semantic model, DAX or the report**: find the relevant skill(s) below,",
        "read their `SKILL.md` in full, then apply it. If the agent already loads these skills",
        "automatically, this block is only an index.",
        "",
        "Common rules:",
        "",
        "- Read-only by default: propose a plan, then get explicit approval before any deletion, rename,",
        "  or change to a relationship or security role.",
        "- Project under Git, clean working tree before writing; never `git push` or publish unless asked.",
        "- Never read or commit `.pbi/cache.abf` (data) or `.pbi/localSettings.json`.",
        "- Never claim a measure was verified if no query was run.",
        "",
        "| Skill | When to read it | File |",
        "|---|---|---|",
    ]
    for s in skills:
        desc = short_description(s["description"]).replace("|", "\\|")
        lines.append(f"| `{s['name']}` | {desc} | `{rel_dest}/{s['name']}/SKILL.md` |")
    lines += ["", END.format(plugin=plugin["name"]), ""]
    return "\n".join(lines)


def update_agents_md(path, plugin_name, block, dry):
    """Replace the existing block, or append it at the end; block=None removes the block."""
    begin, end = BEGIN.format(plugin=plugin_name), END.format(plugin=plugin_name)
    text = read_text(path).replace("\r\n", "\n") if os.path.isfile(path) else ""
    i, j = text.find(begin), text.find(end)
    if i != -1 and j > i:
        before, after = text[:i].rstrip("\n"), text[j + len(end):].lstrip("\n")
    elif block is None:
        return
    else:
        before, after = text.rstrip("\n"), ""
    parts = [p for p in (before, block.rstrip("\n") if block else None, after.rstrip("\n")) if p]
    if not text and block:
        parts.insert(0, "# AGENTS.md\n\nInstructions for the coding agents working on this BI project.")
    new = "\n\n".join(parts) + "\n"
    print(f"  {'[dry run] ' if dry else ''}AGENTS.md : block {plugin_name} "
          f"{'removed' if block is None else 'written'} ({path})")
    if not dry:
        write_text(path, new)


def parse_args(argv):
    opts = {"agent": None, "target": os.getcwd(), "dest": None, "plugin": None, "skills": None,
            "global": False, "agents_md": None, "force": False, "uninstall": False, "dry": False, "list": False}
    flags = {"--global": "global", "--force": "force", "--uninstall": "uninstall", "--dry-run": "dry",
             "--list": "list"}
    values = {"--agent": "agent", "--target": "target", "--dest": "dest", "--plugin": "plugin",
              "--skills": "skills"}
    it = iter(argv)
    for a in it:
        if a in flags:
            opts[flags[a]] = True
        elif a == "--no-agents-md":
            opts["agents_md"] = False
        elif a in values:
            v = next(it, None)
            if v is None:
                raise SystemExit(f"✖  {a} expects a value.")
            opts[values[a]] = v
        elif a in ("-h", "--help"):
            print(__doc__)
            raise SystemExit(0)
        else:
            raise SystemExit(f"✖  Unknown option : {a}\n{__doc__}")
    return opts


def main(argv):
    utf8_console()
    o = parse_args(argv)
    if o["list"]:
        print("Agent     Skills (project)   Skills (personal)     AGENTS.md block")
        for name, (proj, home, block) in AGENTS.items():
            print(f"{name:<9} {proj:<18} {home:<21} {'yes' if block else 'no'}")
        return 0
    if o["agent"] not in AGENTS:
        print(f"✖  --agent required: {', '.join(AGENTS)} (or --list).", file=sys.stderr)
        return 2
    names = plugin_names()
    pname = o["plugin"] or (names[0] if len(names) == 1 else None)
    if pname not in names:
        print(f"✖  --plugin required, one of : {', '.join(names)}.", file=sys.stderr)
        return 2
    plugin = load_plugin(pname)
    proj_dir, home_dir, block_default = AGENTS[o["agent"]]
    target = os.path.abspath(os.path.expanduser(o["target"]))
    if o["global"]:
        base, rel_dest = os.path.expanduser("~"), home_dir[2:]
    else:
        base, rel_dest = target, proj_dir
        if not os.path.isdir(target):
            print(f"✖  Target folder not found : {target}", file=sys.stderr)
            return 2
        if (target + os.sep).lower().startswith((ROOT + os.sep).lower()):
            print("✖  The target is this skills repository: pass the BI project with --target.", file=sys.stderr)
            return 2
    dest = os.path.abspath(os.path.expanduser(o["dest"])) if o["dest"] else os.path.join(base, *rel_dest.split("/"))
    if o["dest"]:
        rel_dest = os.path.relpath(dest, base).replace(os.sep, "/")
    write_block = (block_default if o["agents_md"] is None else o["agents_md"]) and not o["global"]
    agents_dest = os.path.join(base, ".claude", "agents") if o["agent"] == "claude" else None
    manifest_path = os.path.join(dest, f".{pname}-manifest.json")
    previous = json.loads(read_text(manifest_path)) if os.path.isfile(manifest_path) else {}
    dry, tag = o["dry"], "[simulation] " if o["dry"] else ""

    def remove_previous():
        """Remove what the last installation put in place (and nothing else)."""
        for s in previous.get("skills", []):
            p = os.path.join(dest, s)
            if os.path.isfile(os.path.join(p, "SKILL.md")):
                if o["uninstall"]:
                    print(f"  {tag}removed: {p}")
                if not dry:
                    shutil.rmtree(p)
        for a in previous.get("agents", []):
            p = os.path.join(agents_dest or "", a + ".md")
            if agents_dest and os.path.isfile(p):
                if o["uninstall"]:
                    print(f"  {tag}removed: {p}")
                if not dry:
                    os.remove(p)

    if o["uninstall"]:
        if not previous:
            print(f"Nothing to remove: no manifest in {dest}.")
            return 0
        remove_previous()
        if not dry:
            os.remove(manifest_path)
        if not o["global"]:
            update_agents_md(os.path.join(target, "AGENTS.md"), pname, None, dry)
        print(f"✔  {pname} removed from {dest}.")
        return 0

    wanted = set(o["skills"].split(",")) if o["skills"] else None
    skills = [s for s in plugin["skills"] if wanted is None or s["name"] in wanted]
    unknown = (wanted or set()) - {s["name"] for s in skills}
    if unknown or not skills:
        print(f"✖  Unknown skill(s): {', '.join(sorted(unknown)) or '(no skill)'}.", file=sys.stderr)
        return 2
    foreign = [s["name"] for s in skills
               if os.path.exists(os.path.join(dest, s["name"])) and s["name"] not in previous.get("skills", [])]
    if foreign and not o["force"]:
        print(f"✖  Already present in {dest} without having been installed by this script : {', '.join(foreign)}.\n"
              "   Check their content, then rerun with --force to replace them.", file=sys.stderr)
        return 1

    print(f"{tag}{pname} {plugin['version']} → {dest} (agent: {o['agent']})")
    remove_previous()
    for s in skills:
        p = os.path.join(dest, s["name"])
        print(f"  {tag}skill: {s['name']}")
        if not dry:
            if os.path.exists(p):
                shutil.rmtree(p)
            shutil.copytree(s["dir"], p, ignore=shutil.ignore_patterns("__pycache__", "*.pyc", ".gitkeep"))
    agents = plugin["agents"] if agents_dest else []
    for a in agents:
        print(f"  {tag}subagent: {a['name']}")
        if not dry:
            os.makedirs(agents_dest, exist_ok=True)
            shutil.copyfile(a["path"], os.path.join(agents_dest, a["name"] + ".md"))
    if not dry:
        write_text(manifest_path, json.dumps(
            {"plugin": pname, "version": plugin["version"], "agent": o["agent"],
             "skills": [s["name"] for s in skills], "agents": [a["name"] for a in agents]},
            ensure_ascii=False, indent=2) + "\n")
    if write_block:
        update_agents_md(os.path.join(target, "AGENTS.md"), pname, agents_md_block(plugin, skills, rel_dest), dry)
    print(f"✔  {len(skills)} skill(s){f', {len(agents)} subagent(s)' if agents else ''} "
          f"{'to install' if dry else 'installed'}.")
    if o["agent"] == "claude":
        print("   With Claude Code, prefer the marketplace (automatic updates):\n"
              "   claude plugin marketplace add keemboll/keemboll-bi ; "
              f"claude plugin install {pname}@keemboll")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
